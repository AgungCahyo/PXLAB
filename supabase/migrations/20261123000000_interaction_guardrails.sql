-- Interaction guardrails for appreciations and follows.
--
-- `reactions` and `follows` keep the current state. These append-only event
-- tables keep an immutable one-hour history so unfollow / unlike cannot reset
-- the spam allowance. Both state changes go through one SECURITY DEFINER RPC:
-- it serializes per user with an advisory lock, enforces the limit, applies an
-- idempotent write, and returns the authoritative state + count in one call.
-- Limits are passed by the trusted server action, so SQL and app config cannot
-- drift apart.

create table if not exists public.reaction_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  creation_id uuid not null references public.creations (id) on delete cascade,
  desired boolean not null,
  created_at timestamptz not null default now()
);

create index if not exists reaction_events_user_created_at_idx
  on public.reaction_events (user_id, created_at desc);

alter table public.reaction_events enable row level security;
revoke all on table public.reaction_events from anon, authenticated;

create table if not exists public.follow_events (
  id bigint generated by default as identity primary key,
  follower_id uuid not null references public.profiles (id) on delete cascade,
  following_id uuid not null references public.profiles (id) on delete cascade,
  desired boolean not null,
  created_at timestamptz not null default now()
);

create index if not exists follow_events_follower_created_at_idx
  on public.follow_events (follower_id, created_at desc);

alter table public.follow_events enable row level security;
revoke all on table public.follow_events from anon, authenticated;

create or replace function public.set_reaction_state(
  p_creation_id uuid,
  p_desired boolean default null,
  p_limit integer default 60
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_desired boolean;
  v_limited boolean := false;
  v_changed boolean := false;
  v_liked boolean := false;
  v_count bigint := 0;
begin
  if v_user is null then
    return jsonb_build_object('error', 'not_authenticated');
  end if;
  -- The RPC is reachable directly by authenticated clients, so never trust a
  -- caller-supplied limit above the app's configured ceiling.
  if p_limit is null or p_limit < 1 then p_limit := 60; end if;
  if p_limit > 60 then p_limit := 60; end if;

  if not exists (
    select 1 from public.creations c
    where c.id = p_creation_id and c.status = 'published'
  ) then
    return jsonb_build_object('found', false);
  end if;

  -- One lock per user: concurrent taps cannot both pass the limit check.
  perform pg_advisory_xact_lock(hashtext('reaction:' || v_user::text)::bigint);

  delete from public.reaction_events
  where created_at < now() - interval '1 hour';

  select count(*) >= p_limit into v_limited
  from public.reaction_events
  where user_id = v_user and created_at >= now() - interval '1 hour';

  select exists (
    select 1 from public.reactions
    where user_id = v_user and creation_id = p_creation_id
  ) into v_liked;

  select count(*) into v_count
  from public.reactions
  where creation_id = p_creation_id and reaction_type = 'appreciate';

  if v_limited then
    return jsonb_build_object(
      'limited', true,
      'liked', v_liked,
      'count', v_count,
      'changed', false
    );
  end if;

  v_desired := coalesce(p_desired, not v_liked);

  if v_desired then
    insert into public.reactions (user_id, creation_id, reaction_type)
    values (v_user, p_creation_id, 'appreciate')
    on conflict (user_id, creation_id) do nothing;
    v_changed := found;
  else
    delete from public.reactions
    where user_id = v_user and creation_id = p_creation_id;
    v_changed := found;
  end if;

  if v_changed then
    insert into public.reaction_events (user_id, creation_id, desired)
    values (v_user, p_creation_id, v_desired);
  end if;

  select exists (
    select 1 from public.reactions
    where user_id = v_user and creation_id = p_creation_id
  ) into v_liked;

  select count(*) into v_count
  from public.reactions
  where creation_id = p_creation_id and reaction_type = 'appreciate';

  return jsonb_build_object(
    'found', true,
    'limited', false,
    'liked', v_liked,
    'count', v_count,
    'changed', v_changed
  );
end;
$$;

create or replace function public.set_follow_state(
  p_target_user_id uuid,
  p_desired boolean,
  p_limit integer default 40
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_limited boolean := false;
  v_changed boolean := false;
  v_following boolean := false;
begin
  if v_user is null then
    return jsonb_build_object('error', 'not_authenticated');
  end if;
  if p_target_user_id = v_user then
    return jsonb_build_object('self', true);
  end if;
  if p_limit is null or p_limit < 1 then p_limit := 40; end if;
  if p_limit > 40 then p_limit := 40; end if;

  if not exists (select 1 from public.profiles p where p.id = p_target_user_id) then
    return jsonb_build_object('found', false);
  end if;

  perform pg_advisory_xact_lock(hashtext('follow:' || v_user::text)::bigint);

  delete from public.follow_events
  where created_at < now() - interval '1 hour';

  select count(*) >= p_limit into v_limited
  from public.follow_events
  where follower_id = v_user and created_at >= now() - interval '1 hour';

  select exists (
    select 1 from public.follows
    where follower_id = v_user and following_id = p_target_user_id
  ) into v_following;

  if v_limited then
    return jsonb_build_object(
      'limited', true,
      'following', v_following,
      'changed', false
    );
  end if;

  if p_desired then
    insert into public.follows (follower_id, following_id)
    values (v_user, p_target_user_id)
    on conflict (follower_id, following_id) do nothing;
    v_changed := found;
  else
    delete from public.follows
    where follower_id = v_user and following_id = p_target_user_id;
    v_changed := found;
  end if;

  if v_changed then
    insert into public.follow_events (follower_id, following_id, desired)
    values (v_user, p_target_user_id, p_desired);
  end if;

  select exists (
    select 1 from public.follows
    where follower_id = v_user and following_id = p_target_user_id
  ) into v_following;

  return jsonb_build_object(
    'found', true,
    'limited', false,
    'following', v_following,
    'changed', v_changed
  );
end;
$$;

revoke all on function public.set_reaction_state(uuid, boolean, integer) from public, anon;
grant execute on function public.set_reaction_state(uuid, boolean, integer) to authenticated;

revoke all on function public.set_follow_state(uuid, boolean, integer) from public, anon;
grant execute on function public.set_follow_state(uuid, boolean, integer) to authenticated;
